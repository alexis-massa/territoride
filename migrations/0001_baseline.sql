-- (from `pg_dump --schema-only` of the live database). On the live database this is recorded with
-- `territoride baseline`, never run; `just schema-check` proves it equals the live schema.
-- The Django tables (auth_*, django_*, accounts_user_*) are kept so the Python version still runs on the
-- database; the Rust app uses only accounts_user, game_* and (from migration 2) app_sessions.

